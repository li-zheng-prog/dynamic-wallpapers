"""Package embedded installer resources from the app and theme payload directory.
Assign each file a resource ID and generate:
  - payload.rc: one RCDATA entry per file, with IDs starting at 1001.
  - payload_manifest.txt: also embedded as RCDATA ID 2000; the installer reads it
    to determine which files belong to each optional theme.
Manifest format (UTF-8, per line): id|kind|relative path|theme name|bytes

Usage: python pack_setup.py <payload-directory> <output-directory> [<shell-icon> <installed-name>]
"""
import fnmatch
import os
import sys


def collect(payload_dir, shell_icon=None):
    items = []
    nid = 1001
    # Top-level files, including the application executable.
    for name in sorted(os.listdir(payload_dir)):
        if shell_icon and fnmatch.fnmatch(name, "DynamicWallpapers-logo-v*.ico"):
            continue  # Never package an old icon from a reused build directory.
        p = os.path.join(payload_dir, name)
        if os.path.isfile(p):
            items.append((nid, "app", name, "", os.path.getsize(p)))
            nid += 1
    if shell_icon:
        source, name = shell_icon
        items.append((nid, "app", name, "", os.path.getsize(source)))
        nid += 1
    # Themes, each in its own subdirectory.
    tdir = os.path.join(payload_dir, "themes")
    if os.path.isdir(tdir):
        for theme in sorted(os.listdir(tdir)):
            tp = os.path.join(tdir, theme)
            if not os.path.isdir(tp):
                continue
            for root, _dirs, files in os.walk(tp):
                for f in sorted(files):
                    full = os.path.join(root, f)
                    rel = os.path.relpath(full, payload_dir).replace("/", "\\")
                    items.append((nid, "theme", rel, theme, os.path.getsize(full)))
                    nid += 1
    return items


def main():
    if len(sys.argv) not in (3, 5):
        sys.exit("Usage: pack_setup.py <payload-directory> <output-directory> [<shell-icon> <installed-name>]")
    payload_dir = os.path.abspath(sys.argv[1])
    out_dir = os.path.abspath(sys.argv[2])
    os.makedirs(out_dir, exist_ok=True)
    shell_icon = (os.path.abspath(sys.argv[3]), sys.argv[4]) if len(sys.argv) == 5 else None
    items = collect(payload_dir, shell_icon)
    if not items:
        print("!! Payload directory is empty:", payload_dir)
        sys.exit(1)

    manifest_lines = [f"{i[0]}|{i[1]}|{i[2]}|{i[3]}|{i[4]}" for i in items]
    manifest_path = os.path.join(out_dir, "payload_manifest.txt")
    with open(manifest_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(manifest_lines) + "\n")

    rc = ['#include "resource.h"', "", "/* Generated by build/pack_setup.py; do not edit manually. */"]
    for (nid, kind, rel, theme, size) in items:
        source = shell_icon[0] if shell_icon and rel == shell_icon[1] else os.path.join(payload_dir, rel.replace("\\", "/"))
        full = source.replace("\\", "/")
        rc.append(f'{nid} RCDATA "{full}"')
    rc.append(f'2000 RCDATA "{manifest_path.replace(chr(92), "/")}"')
    rc_path = os.path.join(out_dir, "payload.rc")
    with open(rc_path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(rc) + "\n")

    total = sum(i[4] for i in items)
    print(f"payload: {len(items)} files, {total/1024/1024:.1f} MB total")
    for (nid, kind, rel, theme, size) in items[:3]:
        print(f"  [{nid}] {kind} {rel} ({size/1024/1024:.1f} MB)")
    print(f"  ... {len(items)} entries -> {rc_path}")


if __name__ == "__main__":
    main()
